// Writes extension/vendor/m3-tokens.css: the Material 3 colour roles, light and dark, for the extension's
// pages, the overlay and the test page. The UI itself is built by ui-src/ (Lit + @m3e/web).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// material-color-utilities ships extensionless ESM imports that Node cannot load; bundle it first.
const { outputFiles: [colorLib] } = await build({
  stdin: { contents: "export * from '@material/material-color-utilities';", resolveDir: path.dirname(fileURLToPath(import.meta.url)) },
  bundle: true, format: 'esm', platform: 'node', write: false,
});
const { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, SchemeMonochrome, MaterialDynamicColors } = await import('data:text/javascript;base64,' + Buffer.from(colorLib.text).toString('base64'));

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'extension', 'vendor');
fs.mkdirSync(out, { recursive: true });

// "Warm paper and ink": surfaces and containers are tonal spot from a warm seed; the primary is black
// (white in dark), taken from the monochrome scheme. The only strong colour in the UI is the session's.
const SEED = '#8a6a4a';
const kebab = s => s.replace(/[A-Z]/g, c => '-' + c.toLowerCase());
const ROLES = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'secondary', 'onSecondary',
  'secondaryContainer', 'onSecondaryContainer', 'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer', 'background', 'onBackground', 'surface', 'onSurface',
  'surfaceVariant', 'onSurfaceVariant', 'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest', 'inverseSurface', 'inverseOnSurface',
  'inversePrimary', 'outline', 'outlineVariant', 'shadow', 'scrim', 'surfaceTint'];
const INK = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary', 'surfaceTint'];
const vars = isDark => {
  const seed = Hct.fromInt(argbFromHex(SEED));
  const paper = new SchemeTonalSpot(seed, isDark, 0), ink = new SchemeMonochrome(seed, isDark, 0);
  return ROLES.map(r => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(INK.includes(r) ? ink : paper))};`).join('\n');
};
// `.m3-tokens` repeats the roles for a wrapper inside <m3e-theme>, which sets colours of its own on itself.
const css = `/* generated by vendor-src/build.mjs from seed ${SEED} */
:root {
${vars(false)}
}
@media (prefers-color-scheme: dark) {
  :root {
${vars(true).replace(/^/gm, '  ')}
  }
}
.m3-tokens {
${vars(false)}
}
@media (prefers-color-scheme: dark) {
  .m3-tokens {
${vars(true).replace(/^/gm, '  ')}
  }
}
`;
fs.writeFileSync(path.join(out, 'm3-tokens.css'), css);
console.log(`wrote extension/vendor/m3-tokens.css (${fs.statSync(path.join(out, 'm3-tokens.css')).size} B)`);
