// Builds extension/vendor/material-web.js (one ESM bundle) and extension/vendor/m3-tokens.css
// (Material 3 color roles from Chrome's default blue seed, light + dark).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// material-color-utilities ships extensionless ESM imports that Node cannot load; bundle it first.
const { outputFiles: [colorLib] } = await build({
  stdin: { contents: "export * from '@material/material-color-utilities';", resolveDir: path.dirname(fileURLToPath(import.meta.url)) },
  bundle: true, format: 'esm', platform: 'node', write: false,
});
const { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors } = await import('data:text/javascript;base64,' + Buffer.from(colorLib.text).toString('base64'));

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'extension', 'vendor');
fs.mkdirSync(out, { recursive: true });

await build({
  entryPoints: [path.join(here, 'entry.js')],
  bundle: true, format: 'esm', minify: true, target: 'chrome116', legalComments: 'eof',
  outfile: path.join(out, 'material-web.js'),
});

const SEED = '#0b57d0'; // Chrome's GM3 primary blue
const kebab = s => s.replace(/[A-Z]/g, c => '-' + c.toLowerCase());
const ROLES = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'secondary', 'onSecondary',
  'secondaryContainer', 'onSecondaryContainer', 'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer', 'background', 'onBackground', 'surface', 'onSurface',
  'surfaceVariant', 'onSurfaceVariant', 'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
  'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest', 'inverseSurface', 'inverseOnSurface',
  'inversePrimary', 'outline', 'outlineVariant', 'shadow', 'scrim', 'surfaceTint'];
// Chrome's GM3 accent roles; everything else comes from the generated tonal-spot scheme.
const CHROME = {
  light: { primary: '#0b57d0', onPrimary: '#ffffff', primaryContainer: '#d3e3fd', onPrimaryContainer: '#041e49',
    secondaryContainer: '#c2e7ff', onSecondaryContainer: '#001d35', surface: '#ffffff' },
  dark: { primary: '#a8c7fa', onPrimary: '#062e6f', primaryContainer: '#0842a0', onPrimaryContainer: '#d3e3fd',
    secondaryContainer: '#004a77', onSecondaryContainer: '#c2e7ff' },
};
const vars = isDark => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
  const pin = CHROME[isDark ? 'dark' : 'light'];
  return ROLES.map(r => `  --md-sys-color-${kebab(r)}: ${pin[r] || hexFromArgb(MaterialDynamicColors[r].getArgb(scheme))};`).join('\n');
};
const css = `/* generated by vendor-src/build.mjs from seed ${SEED} */
:root {
${vars(false)}
}
@media (prefers-color-scheme: dark) {
  :root {
${vars(true).replace(/^/gm, '  ')}
  }
}
`;
fs.writeFileSync(path.join(out, 'm3-tokens.css'), css);
console.log('wrote', fs.readdirSync(out).map(f => `${f} (${fs.statSync(path.join(out, f)).size} B)`).join(', '));
