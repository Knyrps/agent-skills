// Writes src/overlay/icon-paths.ts: the SVG paths of the few Material Symbols the in-page overlay draws.
// The overlay runs in a content script, where @m3e/icons cannot be imported (it registers custom elements).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const NAMES = ['crop_square', 'arrow_outward', 'draw', 'undo', 'close', 'check', 'delete', 'public'];
const out = {};
for (const n of NAMES) {
  const src = fs.readFileSync(path.join(here, '..', 'node_modules', '@m3e', 'icons', 'dist', 'outlined', n + '.js'), 'utf8');
  const m = /outlined:'([^']+)'/.exec(src);
  if (!m) throw new Error('no outlined path for ' + n);
  out[n] = m[1];
}
fs.writeFileSync(path.join(here, '..', 'src', 'overlay', 'icon-paths.ts'),
  `// Generated by tools/icon-paths.mjs from @m3e/icons (Material Symbols, Apache 2.0). Do not edit.\nexport const ICON_PATHS = ${JSON.stringify(out, null, 2)} as const;\n`);
